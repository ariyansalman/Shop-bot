def normalize_language(lang_code: str) -> str:
    """Return lang_code if it's a supported language, otherwise the default."""
    return lang_code if lang_code in VALID_LANGUAGE_CODES else DEFAULT_LANGUAGE


def t(key: str, lang: str = DEFAULT_LANGUAGE, **kwargs) -> str:
    """Translate a key into the given language, falling back to English.

    Missing keys fall back to English, and finally to the raw key itself, so
    a typo or an unfinished translation never raises or shows a blank string.
    """
    lang = normalize_language(lang)
    template = TRANSLATIONS.get(lang, {}).get(key)
    if template is None:
        template = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        return template.format(**kwargs)
    return template
